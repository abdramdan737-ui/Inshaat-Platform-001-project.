def _body():
    tabs = st.tabs(list(GUIDE))
    for t, (steps, results, tips) in zip(tabs, GUIDE.values()):
        with t:
            if steps:
                st.markdown("**الخطوات**")
                st.markdown("\n".join(f"{i}. {s}" for i, s in enumerate(steps, 1)))
            if results:
                st.markdown("**كيف تقرأ النتيجة**")
                st.markdown("\n".join(f"- {r}" for r in results))
            if tips:
                st.markdown("**نصائح**")
                st.markdown("\n".join(f"- {x}" for x in tips))


if hasattr(st, "dialog"):
    @st.dialog("📖 دليل الاستخدام", width="large")
    def _show():
        _body()
else:                                  # إصدارات Streamlit القديمة
    def _show():
        with st.expander("📖 دليل الاستخدام", expanded=True):
            _body()


def guide_button(key="guide"):
    if st.button("📖 دليل الاستخدام", key=f"gb_{key}", use_container_width=True):
        _show()
